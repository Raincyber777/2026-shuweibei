para(doc, "该值为闭式精确解（σ_ψ(s) 单调递增，判据在 s_max 处恰取等）。")
h2(doc, "V.2 80 m 处的检验")
para(doc, f"名义模型在 s = 80：σ(80) = 1.9 m，σ_ψ = {R['at_80']['sigma_psi_deg']:.4f}° > {R['sigma_psi_max_deg']:.4f}°，"
          f"P = {R['at_80']['P']:.4f} < 0.95，缺口 {R['at_80']['P_deficit']:.4f}；"
          f"σ(80) 超出允许值 {R['at_80']['excess_needed_m']:.4f} m。")
h2(doc, "V.3 (a, b) 的线性约束域")
para(doc, "80 m 处同一要求（且 b ≥ 0 时 σ(s) 单调、80 m 是 s ≤ 80 的最坏点）给出线性不等式：")
para(doc, f"    a ≥ 0,  b ≥ 0,  a + 80·b ≤ σ(s_max) = {R['ab_region']['a_plus_80b_max_m']:.6f} m。", indent=False)
para(doc, f"即三角形可行域：b = 0 时 a ≤ {R['ab_region']['a_max_m']:.4f} m；a = 0 时 "
          f"b ≤ {R['ab_region']['b_max_m_per_m']:.6f} m/m（即每米行驶的定位漂移须从 2 cm 降到 2.048 cm 以下）。"
          f"名义点 (0.3, 0.02) 使 a + 80b = 1.9 m > 1.6384 m，位于域外——需要把斜率降到 "
          f"b ≤ (1.6384 − 0.3)/80 = 0.016731 m/m（−16.3%），或把截距降到 a ≤ 1.6384 − 1.6 = 0.0384 m。")

# ============================ VI ============================
h1(doc, "VI. 近似适用性论证与模型验证")
h2(doc, "VI.1 线性化误差的定量评估")
para(doc, f"精确角 Δα = arctan2(−δ⊥, d − δ∥) 的二阶残差主项为 −δ⊥δ∥/d²，其 RMS = σ(s)²/d²，"
          f"在 s = 80 时为 {R['monte_carlo']['linearization_residual_rms_deg_at80']:.4f}°，"
          f"仅为 σ_ψ 的 4.4%；方差贡献 ≈0.2%。")
