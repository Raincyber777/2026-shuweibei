# ============================ IV ============================
h1(doc, "IV. 误差传播模型的建立")
h2(doc, "IV.1 坐标系与横向投影")
para(doc, "以真实位置 P 为原点、真实视线方向为 x′ 轴建立局部坐标系，则目标位于 (d, 0)。估计位置误差 (δx, δy) 在该系下"
          "分解为横向 δ⊥ 与纵向 δ∥。由于 (δx, δy) 各向同性（每轴独立同方差），旋转不变性给出 δ⊥ ~ N(0, σ(s)²)，"
          "且与 δ∥ 独立——横向投影的方差就等于单轴方差，无需额外换算。")
h2(doc, "IV.2 指令方位角与传播公式")
para(doc, "云台按估计位置 P̂ = P + δ 指向目标，指令方位角相对真实方位角的偏差的精确表达式为"
          " Δα = arctan2(−δ⊥, d − δ∥)（wrap 前）。对 δ ≪ d 一阶展开：Δα = −δ⊥/d + O(δ²/d²)。"
          "加上云台零偏与控制误差后：")
para(doc, "    Δψ = wrap( −δ⊥/d·(180/π) + ε₀ + ε_c )。", indent=False)
h2(doc, "IV.3 合成正态与判据")
para(doc, "三项独立零均值正态（wrap 由 A3 失效），合成严格正态：")
para(doc, "    σ_ψ²(s) = (σ(s)/d · 180/π)² + σ₀² + σ_c² = (σ(s)·1.432395)² + 0.64 + 0.36（deg²），", indent=False)
para(doc, f"其中 1.432395 = (180/π)/40 为米→度的换算系数。概率判据双侧化："
          f"P(|Δψ| ≤ 5°) = 2Φ(5/σ_ψ) − 1 ≥ {R['constants']['confidence']} ⟺ σ_ψ ≤ 5/z_{{0.975}} = "
          f"{R['sigma_psi_max_deg']:.4f}°。")

# ============================ V ============================
h1(doc, "V. 模型求解（闭式为主，MC 为证）")
