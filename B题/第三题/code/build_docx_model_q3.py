          "云台零偏误差与控制误差为独立零均值正态，标准差 0.8° 与 0.6°，且与定位误差独立；目标位置精确已知，"
          "车目水平距离固定 d = 40 m。云台按估计位置计算指向方位角。定义 Δψ 为总指向偏差（按估计位置计算的指令角 + 云台零偏 + 控制误差）相对真实方位角之差"
          "（wrap 到 [−180°, 180°)）。任务：①建立 Δψ 的误差传播模型；②求 P(|Δψ| ≤ 5°) ≥ 0.95 的最大行驶距离；"
          "③若 80 m 处仍须满足同一要求，推导非负参数 (a, b) 的约束；④论证近似/数值方法的适用性并验证；"
