para(doc, f"σ_ψ(s)² ≤ (5/z)² 展开为定位方差判据 σ(s)² ≤ d²(π/180)²·[(5/z)² − σ₀² − σ_c²]。数值上 "
          f"C = √({R['sigma_psi_max_deg']:.6f}² − 1.0) = {np.sqrt(R['sigma_psi_max_deg']**2 - 1.0):.6f}°，"
          f"σ(s_max) = 40·(π/180)·C = {R['sigma_s_at_smax_m']:.6f} m，")
